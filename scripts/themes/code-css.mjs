#!/usr/bin/env node
// Generates app/themes/code.css from app/themes/code-themes.json.
//
// Code blocks are highlighted once with Shiki's CSS-variables theme (lib/source.ts), so every token is
// `color: var(--shiki-token-keyword)` etc. This script derives those variables from real Shiki themes, per site
// theme and scheme, by highlighting sample code in both the variables theme and the real theme and matching them
// character by character (Shiki merges tokens differently per theme).
// Runs automatically before `dev` and `build`; run by hand after editing code-themes.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { codeToTokens, createCssVariablesTheme } from 'shiki';

const config = JSON.parse(readFileSync('app/themes/code-themes.json', 'utf8'));
const varsTheme = createCssVariablesTheme({ name: 'css-variables', variablePrefix: '--shiki-', fontStyle: false });

// Samples in the languages the docs use, chosen to hit every token category.
const samples = [
  ['java', `package com.example; import java.util.List;\n/** Doc comment */\n@Override public final class MyPlugin extends JavaPlugin implements Runnable {\n  private static final int MAX = 42; // comment\n  protected void setup(String name, int count) { if (count > 0 && name != null) { getLogger().info("Hello " + name); } return; }\n  enum Mode { ON, OFF } boolean b = true; Object o = null; char c = 'x'; double d = 1.5e3;\n}`],
  ['json', `{ "Id": "Sword", "MaxDurability": 200, "Enabled": true, "Tags": ["a", null], "Nested": { "Scale": 1.5 } }`],
  ['kotlin', `fun main(args: Array<String>) { val x = 1; println("v = $x") } // c`],
  ['bash', `#!/bin/bash\n# comment\nexport NAME="world"; echo "hi $NAME" | grep -i hi && ./gradlew build --info`],
  ['xml', `<?xml version="1.0"?><project attr="v"><!-- c --><dep>1.0</dep></project>`],
  ['properties', `# comment\nserver.port=25565\nname = value`],
];

const charColors = (tokens) => tokens.flatMap((line) => line.flatMap((t) => [...t.content].map((ch) => [ch, t.color])));
const varSamples = await Promise.all(samples.map(([lang, code]) => codeToTokens(code, { lang, theme: varsTheme })));
const cache = new Map();

async function deriveVars(themeName) {
  if (cache.has(themeName)) return cache.get(themeName);
  const counts = new Map(); // var -> Map(color -> n)
  let fg;
  for (const [i, [lang, code]] of samples.entries()) {
    const real = await codeToTokens(code, { lang, theme: themeName });
    fg ??= real.fg;
    const a = charColors(varSamples[i].tokens);
    const b = charColors(real.tokens);
    for (let k = 0; k < Math.min(a.length, b.length); k++) {
      if (/\s/.test(a[k][0])) continue;
      const v = a[k][1]?.match(/var\((--shiki-[\w-]+)\)/)?.[1];
      if (!v || !b[k][1]) continue;
      if (!counts.has(v)) counts.set(v, new Map());
      const m = counts.get(v);
      m.set(b[k][1], (m.get(b[k][1]) ?? 0) + 1);
    }
  }
  const out = { '--shiki-foreground': fg };
  for (const [v, m] of counts) out[v] = [...m.entries()].sort((x, y) => y[1] - x[1])[0][0];
  // Categories the samples never produced fall back to the theme foreground.
  for (const tc of varsTheme.tokenColors) {
    const v = tc.settings.foreground?.match(/var\((--shiki-[\w-]+)\)/)?.[1];
    if (v && !out[v]) out[v] = fg;
  }
  cache.set(themeName, out);
  return out;
}

const block = (sel, vars) => `${sel} {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;
let css = `/* Generated by scripts/themes/code-css.mjs from app/themes/code-themes.json. Do not edit. */\n`;
css += block(':root:not(.dark)', await deriveVars(config.default.light));
css += block(':root.dark', await deriveVars(config.default.dark));
for (const [id, pair] of Object.entries(config.overrides ?? {})) {
  if (pair.light) css += block(`:root:not(.dark)[data-theme='${id}']`, await deriveVars(pair.light));
  if (pair.dark) css += block(`:root.dark[data-theme='${id}']`, await deriveVars(pair.dark));
}
writeFileSync('app/themes/code.css', css);
console.log(`code.css: ${cache.size} Shiki themes, ${Object.keys(config.overrides ?? {}).length} site-theme overrides`);
