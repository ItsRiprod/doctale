#!/usr/bin/env node
// Theme puller: site themes are shadcn registry items (tweakcn by default), vendored into app/themes/.
//
//   npm run theme:list                  list themes in the registry index
//   npm run theme:sync                  pull every theme in the index (adds new, updates, removes ones that left the index)
//   npm run theme:add -- <name|url|file> [--with-fonts]
//                                       add one extra theme: a registry theme name, any shadcn registry-item URL,
//                                       or a JSON file exported from the tweakcn editor
//   npm run theme:remove -- <id>        drop a theme
//
// Outputs (generated, committed, never hand-edited):
//   app/themes/<id>.css     [data-theme="<id>"] { light vars }  .dark[data-theme="<id>"] { dark vars }
//   app/themes/index.css    @imports every theme file (imported by app/global.css)
//   app/themes/themes.json  manifest: id, label, source, pulledAt, swatch colours
//   app/themes/generated.ts typed theme list for the picker / pre-paint script
// Hand-edited settings (default theme, code theme pairs) live in app/themes/config.ts.
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'app/themes';
const INDEX_URL = 'https://tweakcn.com/r/registry.json';
const ITEM_URL = (name) => `https://tweakcn.com/r/themes/${name}.json`;
const MANIFEST = join(DIR, 'themes.json');

// Only colour tokens + radius are copied. Themes also ship fonts, shadows, letter-spacing and `spacing`;
// `--spacing` drives Tailwind v4's entire spacing scale, so it must never leak in.
const COLOR_VAR = /^(background|foreground|card|popover|primary|secondary|muted|accent|destructive|border|input|ring|chart-\d+|sidebar)(-[a-z-]+)?$/;
const keepVar = (key, withFonts) => COLOR_VAR.test(key) || key === 'radius' || (withFonts && /^font-(sans|mono|serif)$/.test(key));

const [cmd, ...rest] = process.argv.slice(2);
const withFonts = rest.includes('--with-fonts');
const arg = rest.find((a) => !a.startsWith('--'));

const readManifest = () => (existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : []);
const today = () => new Date().toISOString().slice(0, 10);
const titleCase = (id) => id.replace(/[-_]+/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());

async function fetchJson(url) {
  const res = await fetch(url, { headers: { accept: 'application/json' } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

function toTheme(item, source) {
  if (!item?.cssVars?.light || !item?.cssVars?.dark) throw new Error(`${source}: not a shadcn theme (missing cssVars.light/dark)`);
  const id = String(item.name).toLowerCase().replace(/[^a-z0-9-]+/g, '-');
  const pick = (vars) => Object.fromEntries(Object.entries(vars ?? {}).filter(([k]) => keepVar(k, withFonts)));
  const light = { ...pick(item.cssVars.theme), ...pick(item.cssVars.light) };
  const dark = { ...pick(item.cssVars.theme), ...pick(item.cssVars.dark) };
  const missing = ['background', 'foreground', 'primary', 'primary-foreground', 'border'].filter((k) => !light[k] || !dark[k]);
  if (missing.length) console.warn(`  ! ${id}: missing core vars (${missing.join(', ')}). Fumadocs' defaults will show through.`);
  return {
    id,
    label: item.title ?? titleCase(id),
    source,
    pulledAt: today(),
    swatch: {
      light: { background: light.background, primary: light.primary },
      dark: { background: dark.background, primary: dark.primary },
    },
    light,
    dark,
  };
}

function writeThemeCss(t) {
  const block = (sel, vars) => `${sel} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}\n`;
  const css =
    `/* Generated by scripts/themes/pull.mjs. Do not edit; re-pull instead.\n * source: ${t.source}\n * pulled: ${t.pulledAt} */\n` +
    block(`[data-theme='${t.id}']`, t.light) +
    '\n' +
    block(`.dark[data-theme='${t.id}']`, t.dark);
  writeFileSync(join(DIR, `${t.id}.css`), css);
}

function writeOutputs(manifest) {
  manifest.sort((a, b) => a.label.localeCompare(b.label));
  writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(
    join(DIR, 'index.css'),
    `/* Generated by scripts/themes/pull.mjs. Every site theme; imported by app/global.css. */\n` +
      manifest.map((t) => `@import './${t.id}.css';`).join('\n') +
      '\n',
  );
  writeFileSync(
    join(DIR, 'generated.ts'),
    `// Generated by scripts/themes/pull.mjs. Do not edit.\n` +
      `export const themes = ${JSON.stringify(
        manifest.map(({ id, label, swatch }) => ({ id, label, swatch })),
        null,
        2,
      )} as const;\n\nexport type ThemeId = (typeof themes)[number]['id'];\n`,
  );
}

function upsert(manifest, theme) {
  const { light, dark, ...meta } = theme;
  writeThemeCss(theme);
  const i = manifest.findIndex((t) => t.id === theme.id);
  if (i >= 0) manifest[i] = meta;
  else manifest.push(meta);
}

async function main() {
  if (cmd === 'list') {
    const index = await fetchJson(INDEX_URL);
    const have = new Set(readManifest().map((t) => t.id));
    for (const item of index.items) console.log(`${have.has(item.name) ? '✓' : ' '} ${item.name.padEnd(22)} ${item.title ?? ''}`);
    console.log(`\n${index.items.length} themes in ${INDEX_URL} (✓ = pulled)`);
    return;
  }

  if (cmd === 'sync') {
    const index = await fetchJson(INDEX_URL);
    const manifest = readManifest();
    const fromIndex = new Set();
    for (const item of index.items) {
      const theme = toTheme(item, ITEM_URL(item.name));
      fromIndex.add(theme.id);
      upsert(manifest, theme);
    }
    // Themes that came from the index but left it are removed; themes added by URL/file are kept.
    const gone = manifest.filter((t) => t.source.startsWith('https://tweakcn.com/r/themes/') && !fromIndex.has(t.id));
    for (const t of gone) {
      rmSync(join(DIR, `${t.id}.css`), { force: true });
      manifest.splice(manifest.indexOf(t), 1);
    }
    writeOutputs(manifest);
    console.log(`synced ${fromIndex.size} themes from ${INDEX_URL}${gone.length ? `; removed: ${gone.map((t) => t.id).join(', ')}` : ''}`);
    return;
  }

  if (cmd === 'add') {
    if (!arg) throw new Error('usage: theme:add <name|url|file>');
    let item;
    let source;
    if (/^https?:\/\//.test(arg)) [item, source] = [await fetchJson(arg), arg];
    else if (existsSync(arg)) [item, source] = [JSON.parse(readFileSync(arg, 'utf8')), `file:${arg}`];
    else [item, source] = [await fetchJson(ITEM_URL(arg)), ITEM_URL(arg)];
    if (!item.name) item.name = arg.split('/').pop().replace(/\.json$/, '');
    const manifest = readManifest();
    const theme = toTheme(item, source);
    upsert(manifest, theme);
    writeOutputs(manifest);
    console.log(`added ${theme.id} (${theme.label})`);
    return;
  }

  if (cmd === 'remove') {
    const manifest = readManifest().filter((t) => t.id !== arg);
    rmSync(join(DIR, `${arg}.css`), { force: true });
    writeOutputs(manifest);
    console.log(`removed ${arg}`);
    return;
  }

  console.log(readFileSync(new URL(import.meta.url), 'utf8').split('\n').slice(1, 17).join('\n').replace(/^\/\/ ?/gm, ''));
  process.exit(cmd ? 1 : 0);
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
